#!/usr/bin/env python3
"""Generate native macOS string tables from the same catalog embedded in both desktops."""
import itertools,json,pathlib,re,sys
check="--check" in sys.argv
root=pathlib.Path(__file__).resolve().parents[1]
values=json.loads((root/'Sources/NashiCore/Resources/Turkish.json').read_text(encoding='utf-8'))
# Turkish upper case (i→İ, ı→I), except product and key names, which keep Latin capitals (SHIFT, not SHİFT).
latin=set(json.loads((root/'Sources/NashiCore/Resources/LatinWords.json').read_text(encoding='utf-8')))
def turkish_upper(value):return re.sub(r'[^\W\d_]+',lambda m:m.group().upper() if m.group() in latin else m.group().replace('i','İ').replace('ı','I').upper(),value)
values.update({key.upper():turkish_upper(value) for key,value in list(values.items()) if not re.search(r'\{\d\}',key)})
# SwiftUI interpolates strings as %@ and integer counts as %lld.
for key,value in list(values.items()):
 count=len(re.findall(r'\{\d\}',key))
 if count:
  for formats in itertools.product(['%@','%lld'],repeat=count):
   source=key;target=value
   for index,fmt in enumerate(formats):
    source=source.replace('{'+str(index)+'}',fmt)
    target=target.replace('{'+str(index)+'}',fmt)
   values[source]=target
# Literal copy handed to LText or NashiPill must have a Turkish entry, or it silently stays English.
call=re.compile(r'(?:LText\(|NashiPill\(title:)((?:[^()\n]|\([^()\n]*\))*?)(?:\)|,(?:symbol|color):)')
missing=sorted({(source.relative_to(root).as_posix(),literal) for source in (root/'Sources/NashiApp').rglob('*.swift') for match in call.finditer(source.read_text(encoding='utf-8'))
 for literal in re.findall(r'"((?:[^"\\]|\\.)*)"',match.group(1)) if '\\(' not in literal and re.search('[A-Za-z]',literal) and literal not in values})
if missing:raise SystemExit('Missing Turkish copy:\n'+'\n'.join(f'  {path}: {literal}' for path,literal in missing))
for language in ['en','tr']:
 directory=root/'Resources/Localizations'/f'{language}.lproj'
 if not check:directory.mkdir(parents=True,exist_ok=True)
 lines=['/* Generated by scripts/generate-localizations.py; edit Turkish.json. */']
 for key,value in sorted(values.items()):
  if re.search(r'\{\d\}',key):continue
  lines.append(json.dumps(key,ensure_ascii=False)+' = '+json.dumps(key if language=='en' else value,ensure_ascii=False)+';')
 path=directory/'Localizable.strings';expected='\n'.join(lines)+'\n'
 if check:
  if not path.exists() or path.read_text(encoding='utf-8')!=expected:raise SystemExit(f'Stale generated localization table: {path.relative_to(root)}')
 else:path.write_text(expected, encoding='utf-8')
print(f'Generated English/Turkish native tables: {len(values)} keys')
