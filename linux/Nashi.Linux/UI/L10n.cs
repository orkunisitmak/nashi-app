    // Linux templates are tried before the shared catalog so that, for example,
    // "Add or change files" is not caught by the shared "{0} files" template.
    private static readonly (System.Text.RegularExpressions.Regex Pattern,string Target)[] Templates=Linux.Where(x=>x.Key.Contains("{0}",StringComparison.Ordinal)).Select(x=>
        (new System.Text.RegularExpressions.Regex("^"+System.Text.RegularExpressions.Regex.Escape(x.Key).Replace(System.Text.RegularExpressions.Regex.Escape("{0}"),"(.*?)",StringComparison.Ordinal)+"$",System.Text.RegularExpressions.RegexOptions.Singleline,TimeSpan.FromMilliseconds(50)),x.Value)).ToArray();
    internal static string T(string source)
    {
        if(Language!="tr")return source;
        if(Linux.TryGetValue(source,out var value))return value;
        foreach(var (pattern,target) in Templates){var match=pattern.Match(source);if(match.Success)return target.Replace("{0}",T(match.Groups[1].Value),StringComparison.Ordinal);}
        return AppLocalization.Text(source,"tr");
    }
